"""Part 2 capability evaluator V2 (pure Python, simulation-agnostic).

One instance judges ONE attempt at ONE level of ONE capability category, from a stream
of base poses:

  update(t, base_xyz, tilt_deg) -> report dict
  finalize(reason)              -> report dict

Success is region/height based (Part 2 rules only judge whether the obstacle was
surmounted; there is no 1/2-foot rule for Part 2). Fail = fall (tilt > 75 deg or base
height collapse) or timeout (caller finalizes).

Scoring uses comp_score.curve_points with *floor* rounding and the contract's
``score_curve`` (organizer answers 2026-10-22: 10 cm endpoints of high wall / gap are
0 points; fractional points are floored; stability = failure ratio with target 0).

Level specs come from ``config/part2-levels.json`` generated by ``make_part2_levels.py``.
"""
from __future__ import annotations

import json
import math
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

FALL_TILT_DEG = 75.0
FALL_Z_M = 0.15


def _hold_ok(cond: bool, held: float, dt: float) -> tuple[bool, float]:
    held = held + dt if cond else 0.0
    return held > 0.0, held


def curve_points_floor(curve: list[dict], value: float | None, unit: str | None = None) -> int:
    """Piecewise-linear score with floor rounding; below first point = 0."""
    if value is None:
        return 0
    if unit == "bool":
        return int(math.floor(curve[-1]["points"])) if float(value) == 1.0 else 0
    pts = sorted((float(p["value"]), float(p["points"])) for p in curve)
    if not pts:
        return 0
    v = float(value)
    if v <= pts[0][0]:
        return int(math.floor(pts[0][1])) if v == pts[0][0] else 0
    if v >= pts[-1][0]:
        return int(math.floor(pts[-1][1]))
    for (v0, p0), (v1, p1) in zip(pts, pts[1:]):
        if v0 <= v <= v1:
            if v1 == v0:
                return int(math.floor(p1))
            return int(math.floor(p0 + (p1 - p0) * (v - v0) / (v1 - v0)))
    return 0


def score_for_level(contract_part2: dict, category: str, level: float) -> int:
    for obs in contract_part2.get("obstacles", []):
        if obs.get("id") == category:
            return curve_points_floor(obs.get("score_curve", []), level, obs.get("unit"))
    return 0


@dataclass
class Part2Result:
    category: str
    level: float
    unit: str
    status: str = "running"      # running / success / fail
    reason: str = ""
    detail: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {"category": self.category, "level": self.level, "unit": self.unit,
                "status": self.status, "reason": self.reason, "detail": self.detail}


class Part2JudgeV2:
    def __init__(self, level_entry: dict) -> None:
        self.spec = level_entry
        self.category = level_entry["category"]
        self.level = float(level_entry["level"])
        self.unit = level_entry.get("unit", "")
        self.j = level_entry.get("judge", {})
        self.result = Part2Result(self.category, self.level, self.unit)
        self.t = 0.0
        self.held = 0.0
        self.max_z = 0.0
        self.max_z_near = 0.0
        self.wall_crossed = False
        self.wall_contact = False
        self.gap_crossed = False
        self.gap_entered = False
        self.gap_entered_lane = False
        self.trench_contact = False
        self.last_x: float | None = None
        self.last_t: float | None = None
        self.lane_y = float((self.j.get("start") or [0.0, 0.0])[1])

    # ------------------------------------------------------------------ hooks
    def _lateral_ok(self, y: float) -> bool:
        return abs(y - self.lane_y) <= float(self.j.get("lane_half_width", 0.70))

    def _cond(self, x: float, y: float, z: float, ground_feet: set[str], tags: set[str]) -> bool:
        kind = self.j.get("kind")
        if kind == "platform":
            lo, hi = self.j.get("goal_x", [0.0, 0.0])
            return (lo <= x <= hi and z >= self.j["top_z"] + 0.38 and self._lateral_ok(y)
                    and not ground_feet and "platform" in tags)
        if kind == "stairs":
            return (x >= self.j["goal_x_min"] and z >= self.j["top_z"] + 0.38
                    and self._lateral_ok(y) and not ground_feet and "stairs" in tags)
        if kind == "slope":
            return (x >= self.j["goal_x_min"] and z >= self.j["rise_z"] + 0.38
                    and self._lateral_ok(y) and not ground_feet and "slope" in tags)
        if kind == "wall":
            return (self.wall_crossed and self.wall_contact and x >= self.j["goal_x_min"]
                    and self.max_z_near >= max(self.j["wall_h"] + 0.10, 0.55)
                    and self._lateral_ok(y))
        if kind == "gap":
            return (self.gap_crossed and x >= self.j["goal_x_min"]
                    and z >= self.j.get("min_z", 0.3) and self._lateral_ok(y))
        if kind == "plum":
            return (x >= self.j["goal_x_min"] and z >= self.j["goal_z_min"]
                    and self._lateral_ok(y) and not ground_feet and "plum" in tags)
        raise ValueError(f"unknown part2 judge kind: {kind}")

    def update(self, t: float, base_xyz: tuple[float, float, float], tilt_deg: float,
               *, foot_tags: dict[str, set[str]] | None = None,
               ground_feet: set[str] | None = None) -> dict:
        self.t = float(t)
        if self.result.status in ("success", "fail"):
            return self.result.to_dict()
        ground_feet = ground_feet or set()
        tags = {tag for values in (foot_tags or {}).values() for tag in values}
        x, y, z = map(float, base_xyz)
        kind = self.j.get("kind")
        if kind == "gap" and "trench_bottom" in tags:
            self.trench_contact = True
        self.max_z = max(self.max_z, z)
        if kind == "wall":
            if self.last_x is not None:
                wx = float(self.j["wall_x"])
                if ((self.last_x - wx) * (x - wx) <= 0 and abs(x - self.last_x) < 1.0
                        and self._lateral_ok(y)):
                    self.wall_crossed = True
            if "wall" in tags and abs(x - self.j["wall_x"]) <= 0.8:
                self.wall_contact = True
                self.max_z_near = max(self.max_z_near, z)
            self.last_x = x
        elif kind == "gap":
            half = float(self.j.get("width", 0.1)) / 2.0
            gx = float(self.j["gap_x"])
            if self.last_x is not None and abs(x - self.last_x) < 1.0:
                near = (self.last_x - (gx - half)) * (x - (gx - half)) <= 0
                far = (self.last_x - (gx + half)) * (x - (gx + half)) <= 0
                if near:
                    self.gap_entered = True
                    self.gap_entered_lane = self._lateral_ok(y)
                if far and self.gap_entered and self._lateral_ok(y):
                    self.gap_crossed = True
                # A single jump over the whole gap also counts as entered + crossed, but only
                # when the crossing point stays inside the scoring lane.
                if near and far and self._lateral_ok(y):
                    self.gap_entered = True
                    self.gap_entered_lane = True
                    self.gap_crossed = True
            self.last_x = x
        self.result.detail = {"x": round(x, 3), "z": round(z, 3),
                              "max_z": round(self.max_z, 3), "tilt_deg": round(tilt_deg, 2)}
        if tilt_deg > FALL_TILT_DEG:
            self.result.status = "fail"
            self.result.reason = f"fell:tilt={tilt_deg:.1f}"
            return self.result.to_dict()
        if z < FALL_Z_M:
            self.result.status = "fail"
            self.result.reason = f"fell:base_z={z:.2f}"
            return self.result.to_dict()
        if kind == "gap" and self.trench_contact:
            self.result.status = "fail"
            self.result.reason = "trench_bottom_contact"
            return self.result.to_dict()
        if kind == "gap" and self.gap_entered and not self.gap_entered_lane:
            self.result.status = "fail"
            self.result.reason = "gap_bypass_outside_lane"
            return self.result.to_dict()
        cond = self._cond(x, y, z, ground_feet, tags)
        hold_s = float(self.j.get("hold_s", 0.2))
        # hold time is accumulated in finalize/update by caller-provided dt; default 20 ms
        dt = 0.02 if self.last_t is None else max(0.0, self.t - self.last_t)
        self.last_t = self.t
        if cond:
            self.held += dt
            if self.held >= hold_s:
                self.result.status = "success"
                self.result.reason = ""
        else:
            self.held = 0.0   # "hold" means continuous; an interruption resets the timer
        return self.result.to_dict()

    def finalize(self, reason: str = "timeout") -> dict:
        if self.result.status not in ("success", "fail"):
            self.result.status = "fail"
            self.result.reason = reason
        return self.result.to_dict()


# ------------------------------------------------------------------ self-test / conformance
def _entry(category: str, level: float, judge: dict, unit: str = "cm") -> dict:
    return {"category": category, "level": level, "unit": unit, "judge": judge}


def _feed(judge: Part2JudgeV2, samples, dt: float = 0.1, *,
          tags: tuple[str, ...] = (), ground: tuple[str, ...] = ()) -> dict:
    rep = None
    for i, (xyz, tilt) in enumerate(samples):
        foot_tags = {leg: set(tags) for leg in ("FL", "FR", "RL", "RR")}
        rep = judge.update(i * dt, xyz, tilt, foot_tags=foot_tags,
                           ground_feet=set(ground))
    return judge.finalize()


def run_self_test() -> None:
    # platform: must actually get on top
    e = _entry("high_platform", 20, {"kind": "platform", "top_z": 0.2,
                                     "goal_x": [1.9, 3.1], "hold_s": 0.05})
    ok = _feed(Part2JudgeV2(e), [((0, 0, 0.5), 5), ((2.0, 0, 0.5), 5),
                                 ((2.5, 0, 0.65), 5), ((2.5, 0, 0.65), 5),
                                 ((2.5, 0, 0.65), 5)], tags=("platform",))
    assert ok["status"] == "success", ok
    low = _feed(Part2JudgeV2(e), [((0, 0, 0.5), 5), ((1.5, 0, 0.45), 5), ((2.0, 0, 0.45), 5)])
    assert low["status"] == "fail", low

    # B5: "hold" must be continuous; an interruption resets the timer
    e_hold = _entry("high_platform", 20, {"kind": "platform", "top_z": 0.2,
                                          "goal_x": [1.9, 3.1], "hold_s": 0.2})
    interrupted = _feed(Part2JudgeV2(e_hold), [((2.5, 0, 0.65), 5),
                                                ((1.0, 0, 0.45), 5),
                                                ((2.5, 0, 0.65), 5)], tags=("platform",))
    assert interrupted["status"] == "fail", interrupted
    continuous = _feed(Part2JudgeV2(e_hold), [((2.5, 0, 0.65), 5),
                                               ((2.5, 0, 0.65), 5),
                                               ((2.5, 0, 0.65), 5)], tags=("platform",))
    assert continuous["status"] == "success", continuous

    # stairs
    e = _entry("stairs", 20, {"kind": "stairs", "top_z": 0.2, "goal_x_min": 3.3, "hold_s": 0.05})
    rep = _feed(Part2JudgeV2(e), [((0, 0, 0.5), 5), ((2.0, 0, 0.7), 5), ((3.4, 0, 0.75), 5),
                                  ((3.4, 0, 0.75), 5), ((3.4, 0, 0.75), 5)], tags=("stairs",))
    assert rep["status"] == "success", rep
    rep = _feed(Part2JudgeV2(e), [((0, 0, 0.5), 5), ((2.0, 0, 0.55), 5)])
    assert rep["status"] == "fail", rep

    # slope
    e = _entry("slope", 30, {"kind": "slope", "rise_z": 0.866, "goal_x_min": 3.0, "hold_s": 0.05})
    rep = _feed(Part2JudgeV2(e), [((2.0, 0, 0.8), 8), ((3.1, 0, 1.3), 8), ((3.1, 0, 1.3), 8), ((3.1, 0, 1.3), 8)], tags=("slope",))
    assert rep["status"] == "success", rep

    # wall: requires climb evidence near the wall
    e = _entry("high_wall", 30, {"kind": "wall", "wall_x": 2.5, "wall_h": 0.3,
                                 "goal_x_min": 3.0, "climb_z_margin": 0.30, "hold_s": 0.05})
    rep = _feed(Part2JudgeV2(e), [((2.2, 0, 0.9), 10), ((2.5, 0, 0.95), 10),
                                  ((3.1, 0, 0.5), 10), ((3.2, 0, 0.5), 10),
                                  ((3.2, 0, 0.5), 10), ((3.2, 0, 0.5), 10)], tags=("wall",))
    assert rep["status"] == "success", rep
    rep = _feed(Part2JudgeV2(e), [((2.2, 0, 0.5), 5), ((2.6, 0, 0.5), 5), ((3.1, 0, 0.5), 5)])
    assert rep["status"] == "fail", rep

    # gap
    e = _entry("trench", 30, {"kind": "gap", "gap_x": 2.5, "width": 0.3,
                           "goal_x_min": 3.05, "min_z": 0.3, "hold_s": 0.05})
    rep = _feed(Part2JudgeV2(e), [((2.0, 0, 0.5), 5), ((2.6, 0, 0.5), 5), ((3.2, 0, 0.5), 5), ((3.2, 0, 0.5), 5)])
    assert rep["status"] == "success", rep
    rep = _feed(Part2JudgeV2(e), [((2.0, 0, 0.5), 5), ((2.5, 0, 0.1), 70)])
    assert rep["status"] == "fail", rep

    # gap: touching the trench bottom invalidates an otherwise complete crossing
    bottom = _feed(Part2JudgeV2(e), [((2.0, 0, 0.5), 5), ((2.6, 0, 0.5), 5),
                                     ((3.2, 0, 0.5), 5), ((3.2, 0, 0.5), 5)],
                   tags=("trench_bottom",))
    assert bottom["status"] == "fail" and bottom["reason"] == "trench_bottom_contact", bottom
    # gap: crossing the near edge outside the scoring lane is a bypass, even if the robot
    # returns to the lane before the far edge.
    bypass_lane = _feed(Part2JudgeV2(e), [((2.0, 1.0, 0.5), 5), ((2.6, 1.0, 0.5), 5),
                                           ((3.2, 0.0, 0.5), 5), ((3.2, 0.0, 0.5), 5)])
    assert bypass_lane["status"] == "fail", bypass_lane

    # plum
    e = _entry("plum", 1, {"kind": "plum", "goal_x_min": 2.7, "goal_z_min": 0.5, "hold_s": 0.05}, unit="bool")
    rep = _feed(Part2JudgeV2(e), [((1.0, 0.2, 0.6), 5), ((2.0, 0.4, 0.65), 5),
                                  ((2.8, 0.4, 0.65), 5), ((2.8, 0.4, 0.65), 5), ((2.8, 0.4, 0.65), 5)], tags=("plum",))
    assert rep["status"] == "success", rep

    # lateral bypass: the same platform success but 1 m off the lane must not count
    bypass = _feed(Part2JudgeV2(e), [((2.0, 1.0, 0.5), 5), ((2.5, 1.0, 0.65), 5),
                                     ((2.5, 1.0, 0.65), 5), ((2.5, 1.0, 0.65), 5), ((2.5, 1.0, 0.65), 5)],
                   tags=("platform",))
    assert bypass["status"] == "fail", bypass

    # gap: standing on the far side without crossing the trench is not a success
    e_gap = _entry("trench", 30, {"kind": "gap", "gap_x": 2.5, "width": 0.3,
                                   "goal_x_min": 3.05, "min_z": 0.3, "hold_s": 0.05,
                                   "lane_y": 0.0, "lane_half_width": 0.7})
    no_cross = _feed(Part2JudgeV2(e_gap), [((3.2, 0.0, 0.5), 5), ((3.2, 0.0, 0.5), 5),
                                           ((3.2, 0.0, 0.5), 5), ((3.2, 0.0, 0.5), 5)])
    assert no_cross["status"] == "fail", no_cross

    # wall: crossing x at standing height without wall contact is not a climb
    e_wall = _entry("high_wall", 30, {"kind": "wall", "wall_x": 2.5, "wall_h": 0.3,
                                       "goal_x_min": 3.0, "hold_s": 0.05,
                                       "lane_y": 0.0, "lane_half_width": 0.7})
    ground_wall = _feed(Part2JudgeV2(e_wall), [((2.2, 0, 0.45), 5), ((2.6, 0, 0.45), 5),
                                               ((3.1, 0, 0.45), 5), ((3.1, 0, 0.45), 5)])
    assert ground_wall["status"] == "fail", ground_wall

    # plum: standing on the ground before the piles is not a success
    e_plum = _entry("plum", 1, {"kind": "plum", "goal_x_min": 2.7, "goal_z_min": 0.5,
                                 "hold_s": 0.05, "lane_y": 0.4, "lane_half_width": 0.7,
                                 "start": [0.4, 0.4, 0.65, 0.0]}, unit="bool")
    ground_plum = _feed(Part2JudgeV2(e_plum), [((2.8, 0.4, 0.42), 5), ((2.8, 0.4, 0.42), 5)],
                        ground=("FL", "FR"))
    assert ground_plum["status"] == "fail", ground_plum

    # scoring: floor + 10 cm endpoints
    contract = json.loads((Path(__file__).resolve().parents[2] / "comp" / "CONTRACT.json")
                          .read_text(encoding="utf-8"))
    p2 = contract["parts"]["part2"]
    assert score_for_level(p2, "high_platform", 10) == 10, score_for_level(p2, "high_platform", 10)
    assert score_for_level(p2, "high_platform", 35) == 150
    assert score_for_level(p2, "high_wall", 10) == 0
    assert score_for_level(p2, "trench", 10) == 0
    assert score_for_level(p2, "trench", 30) == 300
    assert score_for_level(p2, "trench", 20) == 150
    assert score_for_level(p2, "stairs", 15) == 50
    assert score_for_level(p2, "slope", 20) == 10
    assert score_for_level(p2, "slope", 45) == 200
    assert score_for_level(p2, "plum", 1) == 200
    # floor, not round: gap 25 cm -> 225 (floor of 225.0), wall 25 cm -> 75
    assert score_for_level(p2, "trench", 25) == 225
    print("comp_part2_judge self-test: OK")


if __name__ == "__main__":
    run_self_test()
